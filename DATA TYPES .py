# --------------------------------------------
# 1. Data Types
# --------------------------------------------

age = 99            # Integer
is_old = True       # Boolean
value = None        # NoneType
price = 99.99       # Float
name = "Yuvraj"     # String

print("Age Type:", type(age))
print("Boolean Type:", type(is_old))
print("None Type:", type(value))
print("Float Type:", type(price))
print("String Type:", type(name))


# --------------------------------------------
# 2. Addition Operator (+)
# --------------------------------------------

a = 10
b = 20

addition = a + b

print("\nAddition:", addition)


# --------------------------------------------
# 3. Subtraction Operator (-)
# --------------------------------------------

num1 = 19
num2 = 1

subtraction = num1 - num2

print("Subtraction:", subtraction)


# --------------------------------------------
# 4. Division Operator (/)
# --------------------------------------------

x = 10
y = 10

division = y / x

print("Division:", division)


# --------------------------------------------
# 5. Multiplication Operator (*)
# --------------------------------------------

num1 = 5
num2 = 4

multiplication = num1 * num2

print("Multiplication:", multiplication)


# --------------------------------------------
# 6. Modulus Operator (%)
# --------------------------------------------

num1 = 17
num2 = 5

remainder = num1 % num2

print("Remainder:", remainder)


# --------------------------------------------
# 7. Exponent Operator (**)
# --------------------------------------------

base = 2
power = 3

result = base ** power

print("Power:", result)


# --------------------------------------------
# 8. Floor Division Operator (//)
# --------------------------------------------

number1 = 17
number2 = 5

floor_division = number1 // number2

print("Floor Division:", floor_division)