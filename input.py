# Taking user's name
name = input("Enter your name: ")
print("Name:", name)
print("Data Type:", type(name))

# Taking user's roll number
rollno = input("Enter your roll number: ")
print("Roll Number:", rollno)
print("Data Type:", type(rollno))

# Taking user's email
contact_email = input("Enter your Email ID: ")
print("Email:", contact_email)
print("Data Type:", type(contact_email))